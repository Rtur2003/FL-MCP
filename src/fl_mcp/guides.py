def _genres() -> str:
    rows = ["| Genre | Tempo (min-default-max) | Scale | Swing % | Loudness (LUFS) | Sections |"]
    rows.append("| --- | --- | --- | --- | --- | --- |")
    for key, g in GENRES.items():
        names = ", ".join(s.name for s in g.sections)
        rows.append(
            f"| {key} ({g.name}) | {'-'.join(map(str, g.bpm))} | {g.default_scale} | {g.swing} | "
            f"{g.lufs:g} | {names} |"
        )
    return "\n".join(rows)


def _lufs() -> str:
    return ", ".join(
        f"{k} {g.lufs:g}" for k, g in sorted(GENRES.items(), key=lambda kv: kv[1].lufs)
    )


def _instruments() -> str:
    by_role: dict[str, list[str]] = {}
    for name, info in plugins_kb.kb()["instruments"].items():
        for role in info["role"]:
            by_role.setdefault(role, []).append(f"{name.title()} ({info['note'].rstrip('.')})")
    order = [r for r in ROLE_ORDER if r in by_role] + sorted(set(by_role) - set(ROLE_ORDER))
    return "\n".join(f"- **{role}**: {'; '.join(by_role[role])}" for role in order)


FILLERS = {"genres": _genres, "lufs": _lufs, "instruments": _instruments}


def body(topic: str) -> str:
    """The guide with its live tables filled in (genres, loudness targets, instruments)."""
    if topic not in TOPICS:
        raise KeyError(f"unknown guide '{topic}': use one of {', '.join(TOPICS)}")
    text = resources.files("fl_mcp").joinpath(f"data/guides/{topic}.md").read_text(encoding="utf-8")
    for name, make in FILLERS.items():
        text = text.replace("{{" + name + "}}", make())
    return text.strip() + "\n"


def uri(topic: str) -> str:
    return f"fl://guide/{topic}"
